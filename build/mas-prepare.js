// Mac App Store edition: generates build/mas/generated, which package.json → build.mas.files puts in place of the
// regular files. Together with build/mas/stubs it keeps out of the App Store package every feature that edition cannot
// offer under the App Sandbox (Cyberdog account and teams, secret-manager integrations, SMB, OAuth cloud drives,
// self-update, custom configuration folder), including their interface texts.
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const out = path.join(__dirname, 'mas', 'generated')
const src = file => path.join(root, 'src', file)
const dest = file => path.join(out, 'src', file)

const REMOVED_KEYS = [
  /^update\./,
  /^settings\.(tab\.updates|auto_download|update_.+|config_path.*|config_help|copy_confirm|vaults.*)$/,
  /^config\.unavailable$/,
  /^type\.(smb|dropbox|onedrive|gdrive)$/,
  /^f\.reset_auth$/,
  /^(account|team|space|shared|history|vault|invite)[._]/,
]
const removed = key => REMOVED_KEYS.some(re => re.test(key))

fs.rmSync(out, { recursive: true, force: true })
const write = (file, text) => { fs.mkdirSync(path.dirname(dest(file)), { recursive: true }); fs.writeFileSync(dest(file), text) }
const fresh = file => { const p = dest(file); delete require.cache[require.resolve(p)]; return require(p) }

// i18n.js and the language packs hold one entry per line: drop the lines of removed keys.
const KEY_LINE = /^\s*["']([^"']+)["']\s*:/
function pruneLines(file) {
  const lines = fs.readFileSync(src(file), 'utf8').split('\n')
  return lines.filter(line => {
    const m = KEY_LINE.exec(line)
    if (m) return !removed(m[1])
    // single-line translation blocks of vault settings
    return !/Object\.entries\(\{"settings\.vaults"/.test(line)
  }).join('\n')
}
write('i18n.js', pruneLines('i18n.js'))
for (const file of fs.readdirSync(src('locales'))) write('locales/' + file, pruneLines('locales/' + file))

// workspace/i18n.js builds its entries with code: evaluate it, then emit the remaining entries as data.
const core = fresh('i18n.js')
const before = Object.fromEntries(Object.keys(core.D).map(l => [l, new Set(Object.keys(core.D[l]))]))
require(src('workspace/i18n.js')).apply(core.D)
const added = {}
for (const lang of Object.keys(core.D)) {
  const entries = Object.entries(core.D[lang]).filter(([k]) => !before[lang].has(k) && !removed(k))
  if (entries.length) added[lang] = Object.fromEntries(entries)
}
write('workspace/i18n.js', `// Generated by build/mas-prepare.js for the Mac App Store edition.
function applyWorkspaceTranslations(D){const M=${JSON.stringify(added)};for(const l of Object.keys(D))if(M[l])Object.assign(D[l],M[l])}
if(typeof module!=='undefined')module.exports={apply:applyWorkspaceTranslations};else if(typeof i18n!=='undefined')applyWorkspaceTranslations(i18n.D)
`)

// index.html: no account button, no secret-vault interface.
let html = fs.readFileSync(src('index.html'), 'utf8')
for (const re of [/^\s*<button id="btn-account"[^\n]*\n/m, /^\s*<script src="workspace\/ui\/vault-ui\.js"><\/script>\n/m]) {
  if (!re.test(html)) throw new Error('mas-prepare: index.html no longer matches ' + re)
  html = html.replace(re, '')
}
write('index.html', html)

// Checks: every generated file loads and no removed key is left in any language.
const check = fresh('i18n.js')
for (const code of check.PACK_CODES) check.PACKS[code] = fresh('locales/' + code + '.js')
fresh('workspace/i18n.js').apply(check.D)
const left = []
for (const table of [...Object.values(check.D), ...Object.values(check.PACKS)]) for (const k of Object.keys(table)) if (removed(k)) left.push(k)
if (left.length) throw new Error('mas-prepare: removed keys still present: ' + [...new Set(left)].join(', '))
for (const k of ['bastion.via', 'dialog.close', 'srv.edit_tip', 'settings.title']) if (!check.D.en[k] && !check.D.en[k]) throw new Error('mas-prepare: missing ' + k)
console.log('mas-prepare: generated', path.relative(root, out))
