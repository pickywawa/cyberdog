const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { hasCyberdogConfig, copyCyberdogConfig } = require('../src/config-path')

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cyberdog-config-test-'))
const source = path.join(root, 'source')
const target = path.join(root, 'target')
fs.mkdirSync(path.join(source, 'servers'), { recursive: true })
fs.mkdirSync(path.join(source, 'actions'), { recursive: true })
fs.writeFileSync(path.join(source, 'servers', 'server.json'), '{"name":"server"}')
fs.writeFileSync(path.join(source, 'actions', 'action.json'), '{"name":"deploy"}')
fs.writeFileSync(path.join(source, 'groups.json'), '[]')
fs.writeFileSync(path.join(source, 'paths.json'), '[]')
fs.writeFileSync(path.join(source, 'log-favorites.json'), '[]')
fs.mkdirSync(target)
fs.writeFileSync(path.join(target, 'unrelated.txt'), 'keep')

assert.equal(hasCyberdogConfig(target), false)
copyCyberdogConfig(source, target)
assert.equal(hasCyberdogConfig(target), true)
assert.equal(fs.readFileSync(path.join(target, 'unrelated.txt'), 'utf8'), 'keep')
assert.equal(fs.readFileSync(path.join(target, 'servers', 'server.json'), 'utf8'), '{"name":"server"}')
assert.equal(fs.readFileSync(path.join(target, 'actions', 'action.json'), 'utf8'), '{"name":"deploy"}')
assert.equal(fs.readFileSync(path.join(target, 'paths.json'), 'utf8'), '[]')
assert.equal(fs.readFileSync(path.join(target, 'log-favorites.json'), 'utf8'), '[]')

fs.rmSync(root, { recursive: true })
console.log('ok')
