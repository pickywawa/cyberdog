const assert = require('node:assert/strict')
const fs = require('fs'), os = require('os'), path = require('path')
const AdmZip = require('adm-zip')
const c = require('../src/config-transfer')
const { readList, writeList } = require('../src/persistent-list')
const clients = require('../src/client-import')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cyberdog-bundle-'))
try {
  const data = { groups: [{id:'g',name:'Production',favorite:true}], servers: [{id:'s',name:'API',host:'example.org',port:22,user:'app',group:'g',website:'https://example.org',tags:['production'],downloadDir:'/tmp/downloads',pass:'SECRET',fp:'HOSTKEY',key:'/key'}], actions: [{id:'a',name:'Status',script:'uptime'}], paths: [{id:'p',name:'Logs',path:'/srv/logs',serverId:'s'},{id:'p2',name:'Tmp',path:'/tmp'}] }
  const file = path.join(tmp, 'config.zip')
  const selection = Object.fromEntries(c.TYPES.map(k=>[k,data[k].map(x=>x.id)]))
  const linked = c.linkPaths(data.paths, data.servers)
  const relinked = c.linkPaths(linked, [{ ...data.servers[0], id: 'new-id' }])
  assert.equal(relinked[0].serverId, 'new-id', 'saved endpoint survives recreated server IDs')
  assert.equal(relinked[1].serverId, undefined, 'global paths stay global')
  assert.equal(c.linkPaths(linked, [])[0].serverId, 's', 'missing servers never make private paths global')
  const portable = c.portable(data)
  c.writeBundle(c.select(portable, selection), file)
  const archive = new AdmZip(file)
  assert(archive.getEntry('manifest.json'))
  for(const kind of c.TYPES) assert(archive.getEntries().some(e=>e.entryName.startsWith(kind+'/')))
  const bytes = archive.getEntries().map(e=>e.getData().toString()).join('')
  assert(!bytes.includes('SECRET') && !bytes.includes('HOSTKEY'))
  const read = c.readBundle(file)
  const empty = () => Object.fromEntries(c.TYPES.map(k=>[k,[]]))
  const imported = c.merge(empty(), read)
  assert.deepEqual(imported.added, {groups:1,servers:1,actions:1,paths:2})
  assert.equal(imported.data.paths[0].serverId, imported.data.servers[0].id)
  assert.equal(imported.data.servers[0].group, imported.data.groups[0].id)
  assert.notEqual(imported.data.servers[0].id, 's')
  assert.equal(imported.data.groups[0].favorite, true)
  assert.equal(imported.data.servers[0].website,'https://example.org')
  assert.deepEqual(imported.data.servers[0].tags,['production'])
  assert.equal(imported.data.servers[0].downloadDir,'/tmp/downloads')
  assert.deepEqual(c.merge(imported.data, read).added, {groups:0,servers:0,actions:0,paths:0}, 'reimport is idempotent')
  const current = { ...empty(), servers: [{id:'local',host:'EXAMPLE.ORG',port:22,user:'app',pass:'KEEP'}] }
  const merged = c.merge(current, read)
  assert.equal(merged.data.servers.length,1)
  assert.equal(merged.data.servers[0].pass,'KEEP')
  assert.equal(merged.data.paths[0].serverId,'local')
  assert.equal(current.servers[0].pass,'KEEP')
  const pathOnly = c.select(portable,{groups:[],servers:[],actions:[],paths:['p']})
  c.writeBundle(pathOnly, file)
  assert.equal(c.readBundle(file).servers.length,0)
  assert.equal(c.merge(current,c.readBundle(file)).data.paths[0].serverId,'local')
  assert.equal(c.merge(empty(),c.readBundle(file)).skipped,1,'missing server paths must not become global')
  assert.throws(()=>c.merge(current,{...read,actions:[{name:'bad',script:4}]}))
  assert.equal(current.servers.length,1,'invalid import does not mutate source data')
  const legacy = new AdmZip()
  legacy.addFile('folder/old.json',Buffer.from(JSON.stringify({name:'Legacy',host:'legacy',user:'u',group:'Old'})))
  legacy.writeZip(file)
  assert.equal(c.merge(empty(),c.readBundle(file)).data.groups[0].name,'Old')
  legacy.addFile('manifest.json',Buffer.from('{"format":"cyberdog-config","version":99}')); legacy.writeZip(file)
  assert.throws(()=>c.readBundle(file),/Unsupported/)
  const saved = path.join(tmp,'data','paths.json')
  writeList(saved,data.paths)
  writeList(saved,[...data.paths,{id:'p3',path:'/var'}])
  assert.equal(readList(saved).length,3)
  fs.writeFileSync(saved,'{"truncated":')
  assert.equal(readList(saved).length,2,'recover previous valid paths after interrupted/corrupt write')
  fs.unlinkSync(saved)
  assert.equal(readList(saved).length,2,'backup survives missing primary file')
  writeList(saved,[])
  assert.deepEqual(readList(saved),[], 'intentionally deleted paths are not restored from backup')
  fs.writeFileSync(saved,'corrupt');fs.unlinkSync(saved+'.bak')
  assert.throws(()=>readList(saved),'corrupt data is never silently treated as empty')
  const xml = '<FileZilla3><Servers><Folder>Prod<Server><Name>API &amp; SSH</Name><Host>api.test</Host><Port>2222</Port><Protocol>1</Protocol><User>app</User><Pass>SECRET</Pass></Server><Server><Host>ftp.test</Host><Protocol>0</Protocol></Server></Folder></Servers></FileZilla3>'
  const sites = clients.filezilla(xml)
  assert.equal(sites.length,2);assert.deepEqual([sites[1].type,sites[1].host,sites[1].port,sites[1].security],['ftp','ftp.test',21,'explicit']);assert.equal(sites[0].name,'API & SSH');assert.equal(sites[0].group,'Prod');assert.equal(sites[0].port,2222);assert.equal(sites[0].pass,undefined)
  assert.throws(()=>clients.filezilla('<!DOCTYPE x [<!ENTITY e "oops">]><FileZilla3/>'))
  assert.throws(()=>clients.filezilla('<Other/>'))
  const ini = '[Sessions\\Default%20Settings]\nUserName=default\n[Sessions\\Prod/API%20SSH]\nHostName=api.test\nPortNumber=2222\nFSProtocol=2\nPassword=SECRET\n[Sessions\\FTP]\nHostName=ftp.test\nFSProtocol=5\n'
  const sessions=clients.winscp(ini)
  assert.equal(sessions.length,2);assert.deepEqual([sessions[1].type,sessions[1].host,sessions[1].port,sessions[1].security],['ftp','ftp.test',21,'none']);assert.equal(sessions[0].name,'API SSH');assert.equal(sessions[0].group,'Prod');assert.equal(sessions[0].user,'default');assert.equal(sessions[0].port,2222);assert.equal(sessions[0].pass,undefined)
  console.log('configuration transfer and persistence ok')
} finally { fs.rmSync(tmp,{recursive:true,force:true}) }
