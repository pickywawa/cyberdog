// Run: npx electron test/manual/settings-ui.cjs. Launches an actual community copy without private files.
const {app,net}=require('electron'),fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'../..'),temp=fs.mkdtempSync(path.join(os.tmpdir(),'cyberdog-community-'))
app.setPath('appData',path.join(temp,'profile'));fs.mkdirSync(app.getPath('appData'),{recursive:true})
fs.cpSync(path.join(root,'src'),path.join(temp,'src'),{recursive:true,filter:source=>path.basename(source)!=='premium-runtime'})
fs.mkdirSync(path.join(temp,'build'));fs.copyFileSync(path.join(root,'build/icon.png'),path.join(temp,'build/icon.png'))
fs.copyFileSync(path.join(root,'package.json'),path.join(temp,'package.json'))
fs.symlinkSync(path.join(root,'node_modules'),path.join(temp,'node_modules'),process.platform==='win32'?'junction':'dir')
net.fetch=async()=>new Response('{}',{status:503})
app.on('quit',()=>fs.rmSync(temp,{recursive:true,force:true}))
app.on('browser-window-created',(_,win)=>win.webContents.once('did-finish-load',async()=>{
 try{
  const js=code=>win.webContents.executeJavaScript(code),pause=()=>new Promise(resolve=>setTimeout(resolve,150))
  await new Promise(resolve=>setTimeout(resolve,650));assert.equal(await js(`api.premiumAvailable`),false)
  assert.equal(await js(`document.querySelector('#btn-vaults')`),null)
  await js(`void openSettingsModal()`);await pause()
  assert.equal(await js(`document.querySelectorAll('.settings-nav-item').length`),4)
  assert(await js(`!!document.querySelector('#btn-settings svg')`),'community bootstrap applies icons and translations')
  assert.equal(await js(`document.querySelectorAll('.settings-premium-mark').length`),1)
  assert(await js(`!!document.querySelector('.settings-save svg')`))
  assert.equal(await js(`getComputedStyle(document.querySelector('.settings-card')).backgroundColor`),await js(`getComputedStyle(document.body).backgroundColor`),'settings use the same background as the app, like Cyberfox')
  assert(await js(`document.querySelector('.settings-nav').getBoundingClientRect().right<=document.querySelector('.settings-panels').getBoundingClientRect().left+1`))
  await js(`document.querySelector('#settings-tab-vaults').click()`)
  assert(await js(`document.querySelector('.premium-placeholder')!==null`))
  await js(`document.querySelector('#settings-tab-general').focus();document.querySelector('#settings-tab-general').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}))`)
  assert.equal(await js(`document.querySelector('#settings-tab-editor').getAttribute('aria-selected')`),'true')
  await js(`document.querySelector('#settings-tab-general').click()`);await pause();await js(`new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))`);await pause()
  fs.writeFileSync(path.join(os.tmpdir(),'cyberdog-community-settings.png'),(await win.webContents.capturePage()).toPNG())
  await js(`document.querySelector('.settings-card .settings-head button').click();void serverForm()`);await pause()
  assert.equal(await js(`document.querySelector('#modal select')`),null,'community server form needs no cloud location selector')
  await js(`const inputs=document.querySelectorAll('#modal input');inputs[0].value='Community';inputs[1].value='127.0.0.1';inputs[3].value='test';document.querySelector('#modal form').requestSubmit()`);await pause()
  assert.equal((await js(`api.invoke('servers:list')`)).length,1)
  console.log('Community Electron passed: no private modules, free local server creation, left settings navigation, keyboard tabs and Premium placeholder.')
  app.quit()
 }catch(error){console.error(error);app.exit(1)}
}))
setTimeout(()=>app.exit(1),20000).unref()
require(path.join(temp,'src/main.js'))
