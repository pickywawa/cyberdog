const assert = require('node:assert/strict')
const fs = require('fs'), os = require('os'), path = require('path'), cp = require('child_process')
const { utils } = require('ssh2')
const certs = require('../src/certificates')
const keys = require('../src/ssh-keys')
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'cyberdog-security-'))
const shellQuote = s => "'" + s.replace(/'/g, "'\\''") + "'"
;(async () => {
  const directory = path.join(temp,"certs with 'quotes'")
  fs.mkdirSync(directory)
  const certFile = path.join(directory,'server.crt'), privateFile = path.join(directory,'private.pem')
  cp.execFileSync('openssl',['req','-x509','-newkey','rsa:2048','-nodes','-days','30','-subj','/CN=example.test','-keyout',privateFile,'-out',certFile],{stdio:'ignore'})
  const scan = cp.spawnSync('sh',['-s'],{input:certs.scanScript(directory),encoding:'utf8'})
  assert.equal(scan.status,0,scan.stderr)
  const result = certs.parseScan(scan.stdout)
  assert.equal(result.certificates.length,1,'only the certificate is transmitted, not the private key')
  const c = result.certificates[0]
  assert(c.subject.includes('CN=example.test'))
  assert.equal(c.paths[0],certFile)
  assert.equal(certs.status(c,30,c.validTo+1).expired,true)
  assert.equal(certs.status(c,7,c.validTo-5*86400000).level,'warn')
  assert.equal(certs.status(c,7,c.validFrom-1).notYetValid,true)
  assert.equal(certs.status(c,7,c.validTo-20*86400000).level,'ok')
  const der=cp.execFileSync('openssl',['x509','-in',certFile,'-outform','DER']).toString('base64')
  const managed = certs.parseScan(`CERTBOT:1\0/etc/letsencrypt/live/example.test/fullchain.pem\0${der}\0/another.crt\0${der}\0`)
  assert.equal(managed.certbot,true)
  assert.equal(certs.parseScan('CERTBOT:0\0@@LIMIT\0' + '300\0').truncated,true)
  assert.equal(managed.certificates.length,1,'duplicate fingerprints are grouped')
  assert.equal(managed.certificates[0].paths.length,2)
  assert.equal(managed.certificates[0].certName,'example.test')
  assert.throws(()=>certs.scanScript('relative/path'))
  assert.throws(()=>certs.scanScript('/tmp\ncommand'))
  assert.throws(()=>certs.renewScript('example;reboot'))
  assert(!certs.renewScript('example.test').includes('--force-renewal'))
  assert.equal(cp.spawnSync('sh',['-n'],{input:certs.renewScript('example.test')}).status,0)
  const store=keys.createKeyStore(path.join(temp,'keys'),path.join(temp,'registry.json'))
  const key=await store.generate({name:'Test',type:'ed25519',comment:'app@test',passphrase:'test passphrase'})
  assert.equal(key.encrypted,true)
  assert.equal(fs.statSync(key.privatePath).mode & 0o777,0o600)
  assert(!(utils.parseKey(fs.readFileSync(key.privatePath),'test passphrase') instanceof Error))
  assert(utils.parseKey(fs.readFileSync(key.privatePath),'wrong') instanceof Error)
  assert(cp.execFileSync('ssh-keygen',['-lf',key.publicPath,'-E','sha256'],{encoding:'utf8'}).includes(key.fingerprint))
  assert(!JSON.stringify(key).includes('PRIVATE KEY'))
  assert(!fs.readFileSync(path.join(temp,'registry.json'),'utf8').includes('test passphrase'))
  assert.equal(store.importPublic(key.publicPath).id,key.id)
  assert.equal(store.list().length,1,'importing the same public key is idempotent')
  await assert.rejects(store.generate({name:'Bad',type:'unknown'}))
  assert.throws(()=>keys.publicInfo('command="bad" '+key.publicKey))
  assert.throws(()=>keys.publicInfo(key.publicKey+'\n'+key.publicKey))
  const remote=path.join(temp,'remote-ssh')
  const runInstall = () => cp.spawnSync('sh',['-s'],{input:keys.installScript(key.publicKey).replace('d="$HOME/.ssh"','d='+shellQuote(remote)),encoding:'utf8'})
  fs.mkdirSync(remote)
  const other=(await keys.generateValidatedKeyPair('ed25519',{})).public
  fs.writeFileSync(path.join(remote,'authorized_keys'),'# existing entry\n# '+key.publicKey+'\n'+other+'\n')
  assert.equal(runInstall().stdout.trim(),'ADDED')
  assert.equal(runInstall().stdout.trim(),'EXISTS')
  const installed=fs.readFileSync(path.join(remote,'authorized_keys'),'utf8')
  assert(installed.includes(other),'existing access is preserved')
  assert.equal(installed.split('\n').filter(line=>line===key.publicKey).length,1,'no duplicate installation')
  assert.equal(fs.statSync(path.join(remote,'authorized_keys')).mode & 0o777,0o600)
  fs.unlinkSync(path.join(remote,'authorized_keys'))
  const outside=path.join(temp,'outside');fs.writeFileSync(outside,'keep')
  fs.symlinkSync(outside,path.join(remote,'authorized_keys'))
  const rejected=runInstall()
  assert.notEqual(rejected.status,0)
  assert.equal(fs.readFileSync(outside,'utf8'),'keep','symlink target is untouched')
  console.log('certificate scan, expiry and SSH keys ok')
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>fs.rmSync(temp,{recursive:true,force:true}))
