// Run: test/db-lab/lab.sh up, then CYBERDOG_DB_LAB_PORT=<port> npx electron test/smoke/db-ui.cjs
// The databases panel against a real server over SSH (test/db-lab): discovery of the services and Docker containers,
// overview, data browser, SQL editor (read only, then writing), sessions, users and rights, backup, log, Redis keys,
// commands, a login typed in the panel.
const { app } = require('electron'), fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict'), cp = require('node:child_process')
const root = path.resolve(__dirname, '../..'), lab = path.join(root, 'test/db-lab'), port = Number(process.env.CYBERDOG_DB_LAB_PORT)
if (!port || !fs.existsSync(path.join(lab, '.key'))) { console.error('Start the lab first: test/db-lab/lab.sh up'); process.exit(2) }
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'cyberdog-db-ui-'))
const shots = process.env.CYBERDOG_SHOTS || temp
app.setPath('appData', path.join(temp, 'profile'))
const settingsFile = path.join(temp, 'profile', 'Cyberdog', 'settings.json')
fs.mkdirSync(path.dirname(settingsFile), { recursive: true })
fs.writeFileSync(settingsFile, JSON.stringify({ lang: process.env.CYBERDOG_LANG || 'fr', theme: 'dracula' }))
app.on('quit', () => fs.rmSync(temp, { recursive: true, force: true }))
const ssh = cmd => cp.execFileSync('ssh', ['-q', '-i', path.join(lab, '.key'), '-p', String(port), '-o', 'StrictHostKeyChecking=no', '-o', 'UserKnownHostsFile=/dev/null', 'admin@127.0.0.1', cmd], { encoding: 'utf8' })

app.on('browser-window-created', (_, win) => win.webContents.once('did-finish-load', async () => {
  try {
    win.webContents.on('console-message', (...a) => { const m = a[0]?.message ?? a[2]; if ((a[0]?.level ?? a[1]) === 'error' || a[1] >= 3) console.error('renderer:', m) })
    const js = code => win.webContents.executeJavaScript(code).catch(e => { console.error('step failed:', code.slice(0, 160)); throw e }), pause = (ms = 250) => new Promise(r => setTimeout(r, ms))
    const wait = async (test, label, tries = 200) => { for (let i = 0; i < tries; i++) { if (await js(test)) return; await pause(100) } await shot('timeout'); throw Error('timeout: ' + label + '\n' + (await js('__t.text()').catch(() => ''))) }
    const shot = async name => fs.writeFileSync(path.join(shots, `db-${name}.png`), (await win.webContents.capturePage()).toPNG())
    await wait(`typeof openFiles === 'function' && typeof renderDatabases === 'function'`, 'app ready')
    win.setSize(1500, 950)
    // helpers: the panel's text, a clickable row by its title, a view tab
    await js(`window.confirm = () => true
      window.__t = { tab: () => tabs.find(t => t.id === activeId), body: () => __t.tab().dbsBody, text: () => __t.body()?.innerText || '',
        row: title => [...__t.body().querySelectorAll('.dk')].find(r => r.querySelector('b')?.textContent.startsWith(title)),
        view: label => [...__t.body().querySelectorAll('.db-views button')].find(b => b.title === label),
        S: () => __t.tab().dbs.per[__t.tab().dbs.inst], inst: id => { const D = __t.tab().dbs; D.inst = id; D.view = 'overview'; paintDbs(__t.tab()); loadDbView(__t.tab()) } }; true`)
    const servers = await js(`api.invoke('servers:save', { name: 'DB lab', host: '127.0.0.1', port: ${port}, user: 'admin', authMode: 'key', key: ${JSON.stringify(path.join(lab, '.key'))} })`)
    const server = servers.find(s => s.name === 'DB lab')
    await js(`void openFiles(${JSON.stringify(server)})`)
    await wait(`!!__t.tab()?.connId`, 'ssh tab open')

    // ---- discovery ----
    await js(`setPanel(__t.tab(), 'databases')`)
    assert.equal(await js(`__t.tab().rpanelTitle.textContent`), 'Bases de données')
    assert.equal(await js(`__t.tab().rpanel.classList.contains('wide')`), true, 'a wide panel, like the editor')
    await wait(`__t.tab().dbs.loaded`, 'discovery')
    const ids = await js(`__t.tab().dbs.list.map(x => x.id + ' ' + x.status)`)
    for (const id of ['local:postgres:5432 running', 'local:mysql:3306 running', 'local:redis:6379 running', 'docker:lab-analytics-pg running', 'docker:lab-cache-redis running', 'docker:lab-legacy-mysql running']) assert.ok(ids.includes(id), id + ' in ' + ids)
    assert.equal(await js(`__t.tab().dbs.list.some(x => 'secret' in x)`), false, 'container passwords stay in main')
    assert.ok((await js('__t.text()')).includes('sudo · postgres'))
    await shot('list')

    // ---- PostgreSQL: overview ----
    await js(`__t.row('PostgreSQL 15').click()`)
    await wait(`!!__t.body().querySelector('.db-tile') || !!__t.body().querySelector('.db-err')`, 'pg overview')
    assert.ok((await js('__t.text()')).match(/15\.\d+/), 'server version shown')
    assert.ok((await js('__t.text()')).includes('postgres'), 'connected as postgres')
    await shot('pg-overview')

    // ---- data: databases, tables, rows, structure ----
    await js(`__t.view('Données').click()`)
    await wait(`!!__t.row('shop')`, 'databases')
    assert.ok(await js(`!!__t.row('wiki') && __t.row('postgres').classList.contains('db-sys')`))
    await js(`__t.row('shop').click()`)
    await wait(`!!__t.row('customers')`, 'tables')
    assert.ok((await js('__t.text()')).includes('paid_orders'), 'views listed')
    await js(`__t.row('customers').click()`)
    await wait(`__t.body().querySelectorAll('.db-grid tbody tr').length === 100`, 'first page')
    assert.ok((await js('__t.text()')).includes('Lignes 1 à 100'))
    assert.ok(await js(`[...__t.body().querySelectorAll('.db-grid td.null')].length > 0`), 'NULL shown apart')
    await shot('pg-rows')
    await js(`__t.body().querySelector('[title="Page suivante"]').click()`)
    await wait(`__t.text().includes('Lignes 101 à 200')`, 'second page')
    await js(`[...__t.body().querySelectorAll('.seg button')].find(b => b.textContent === 'Structure').click()`)
    await wait(`__t.text().includes('customers_email_key')`, 'structure with indexes')
    assert.ok((await js('__t.text()')).includes('timestamp with time zone'))

    // ---- SQL editor ----
    await js(`__t.view('SQL').click()`)
    await wait(`!!__t.S().sql.editor`, 'monaco')
    assert.equal(await js(`__t.S().sql.db`), 'shop', 'the database being browsed')
    await js(`__t.S().sql.editor.setValue("SELECT country, count(*) AS n FROM customers GROUP BY 1 ORDER BY 1;\\nSELECT name, notes FROM customers WHERE id = 3;"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.results`, 'select results')
    let R = await js(`__t.S().sql.results`)
    assert.deepEqual(R.results[0].rows, [['DE', '500'], ['ES', '500'], ['FR', '500'], ['IT', '500'], ['US', '500']])
    assert.deepEqual(R.results[1].rows, [['Customer 3', 'line one\nline, "two"']])
    await shot('pg-sql')
    // read only: refused before running, and by the server for what slips through
    await js(`__t.S().sql.editor.setValue("UPDATE products SET stock = stock + 1 WHERE id = 1;"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.error`, 'read-only refusal')
    assert.ok((await js(`__t.S().sql.error`)).includes('UPDATE'))
    await js(`__t.S().sql.editor.setValue("WITH d AS (DELETE FROM order_lines WHERE order_id = 1 RETURNING *) SELECT count(*) FROM d;"); __t.S().sql.results = null; runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.results`, 'server read-only')
    assert.match((await js(`__t.S().sql.results.error.message`)), /read-only transaction/)
    const before = ssh(`sudo -u postgres psql -XAtq -d shop -c 'select stock from products where id = 1'`).trim()
    // writing allowed (confirmed)
    await js(`__t.S().sql.readOnly = false; __t.S().sql.editor.setValue("UPDATE products SET stock = stock + 1 WHERE id = 1;\\nSELECT stock FROM products WHERE id = 1;"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.results && !__t.S().sql.running`, 'write')
    R = await js(`__t.S().sql.results`)
    assert.equal(R.results[0].affected, 1)
    assert.equal(R.results[1].rows[0][0], String(+before + 1))
    // a psql meta command never reaches psql
    await js(`__t.S().sql.editor.setValue("select 1 \\\\! touch /tmp/pwned"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.error`, 'meta refused')
    assert.equal(ssh('test -e /tmp/pwned && echo yes || echo no').trim(), 'no')
    await js(`__t.S().sql.readOnly = true; true`)

    // ---- sessions: a long query of another client, cancelled ----
    const sleeper = cp.spawn('ssh', ['-q', '-i', path.join(lab, '.key'), '-p', String(port), '-o', 'StrictHostKeyChecking=no', '-o', 'UserKnownHostsFile=/dev/null', 'admin@127.0.0.1', `sudo -u postgres psql -X -d shop -c 'select pg_sleep(60)'`], { stdio: 'ignore' })
    await js(`__t.view('Sessions').click()`)
    await wait(`__t.text().includes('pg_sleep')`, 'running query listed')
    await shot('pg-sessions')
    await js(`[...__t.body().querySelectorAll('.db-session')].find(r => r.innerText.includes('pg_sleep')).querySelector('[title="Annuler la requête"]').click()`)
    await wait(`!__t.text().includes('pg_sleep(60)')`, 'query cancelled')
    sleeper.kill()

    // ---- users and rights ----
    await js(`__t.view('Utilisateurs').click()`)
    await wait(`!!__t.row('reporting')`, 'roles')
    assert.ok((await js(`__t.row('postgres').innerText`)).includes('superutilisateur'))
    assert.ok((await js(`__t.row('reporting').innerText`)).includes('5 connexions max'))
    await js(`__t.row('reporting').click()`)
    await wait(`!!__t.S().user?.data`, 'grants')
    const grants = await js(`__t.S().user.data.results[1].rows.map(r => r.slice(1).join(' '))`)
    assert.deepEqual(grants, ['customers SELECT', 'orders SELECT'])
    assert.ok((await js(`__t.S().user.data.results[0].rows.find(r => r[0] === 'shop')[1]`)).includes('CONNECT'))
    await shot('pg-grants')

    // ---- backup of a database, downloaded later ----
    await js(`dbBackup(__t.tab(), curInst(__t.tab()), 'shop'); true`)
    await wait(`!!__t.S().backup || __t.S().backingUp === null`, 'backup', 600)
    const bk = await js(`__t.S().backup`)
    assert.ok(bk && bk.path.startsWith('/home/admin/cyberdog-backups/postgres-5432-shop-') && bk.size > 50000, JSON.stringify(bk))
    assert.ok(ssh(`gunzip -c ${bk.path} | grep -c 'COPY public.customers'`).trim() === '1', 'a real pg_dump')

    // ---- log ----
    await js(`__t.view('Journal').click()`)
    await wait(`!!__t.S().log && __t.S().log.S.lines.length > 0`, 'log lines')
    await shot('pg-log')

    // ---- MariaDB ----
    await js(`__t.inst('local:mysql:3306')`)
    await wait(`__t.text().includes('MariaDB') && !!__t.body().querySelector('.db-tile')`, 'mariadb overview')
    await js(`__t.view('Données').click()`)
    await wait(`!!__t.row('blog')`, 'schemas')
    await js(`__t.row('blog').click()`)
    await wait(`!!__t.row('posts')`, 'blog tables')
    await js(`__t.row('users').click()`)
    await wait(`__t.body().querySelectorAll('.db-grid tbody tr').length === 100`, 'blog users')
    assert.ok(await js(`[...__t.body().querySelectorAll('.db-grid td')].some(td => td.title === 'Bio with\\ttab and\\nnewline 1')`), 'escapes decoded')
    await js(`__t.view('SQL').click()`)
    await wait(`!!__t.S().sql.editor`, 'mysql editor')
    assert.equal(await js(`__t.S().sql.db`), 'blog')
    await js(`__t.S().sql.editor.setValue("SELECT title, views FROM posts ORDER BY views DESC LIMIT 3; SHOW TABLES;"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.results`, 'mysql results')
    R = await js(`__t.S().sql.results`)
    assert.deepEqual(R.results[0].rows[0], ['Post #3000 — été', '9000'], 'utf-8 kept')
    assert.deepEqual(R.results[1].rows.map(r => r[0]), ['comments', 'posts', 'users'])
    await js(`__t.view('Utilisateurs').click()`)
    await wait(`!!__t.row('blog@localhost')`, 'mysql users')
    await js(`__t.row('blog@localhost').click()`)
    await wait(`__t.text().includes('GRANT ALL PRIVILEGES ON \`blog\`.*')`, 'show grants')
    await js(`__t.view('Journal').click()`)
    await wait(`!!__t.S().log && __t.S().log.S.lines.length > 0`, 'mariadb log')

    // ---- Redis on the server ----
    await js(`__t.inst('local:redis:6379')`)
    await wait(`!!__t.body().querySelector('.db-tile')`, 'redis overview')
    assert.ok((await js('__t.text()')).includes('7.0.15'))
    await js(`__t.view('Clés').click()`)
    await wait(`!!__t.row('user:42')`, 'keys')
    await js(`__t.row('user:42').click()`)
    await wait(`__t.text().includes('ada@example.com')`, 'hash value')
    await shot('redis-key')
    await js(`__t.S().redis.key = null; __t.S().redis.db = '2'; loadKeys(__t.tab(), true); true`)
    await wait(`!!__t.row('cache:other')`, 'keys of db2')
    await js(`__t.view('Commandes').click()`)
    await wait(`!!__t.S().sql.editor`, 'redis editor')
    await js(`__t.S().sql.db = '0'; __t.S().sql.editor.setValue("ZRANGE leaderboard 0 -1 WITHSCORES\\nTTL session:abc123"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.results`, 'redis commands')
    R = await js(`__t.S().sql.results`)
    assert.ok(R.results[0].text.includes('"grace"') && /\(integer\) \d+/.test(R.results[1].text))
    await js(`__t.S().sql.editor.setValue("FLUSHALL"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.error`, 'redis read only')
    assert.equal(ssh('redis-cli dbsize').trim(), '7', 'nothing flushed')
    await js(`__t.view('Clients').click()`)
    await wait(`__t.text().includes('client|list') || __t.text().includes('client')`, 'redis clients')

    // ---- containers ----
    await js(`__t.inst('docker:lab-analytics-pg')`)
    await wait(`!!__t.body().querySelector('.db-tile')`, 'container overview')
    assert.ok((await js('__t.text()')).includes('analytics'), 'connected as the container user')
    await js(`__t.view('Données').click()`)
    await wait(`!!__t.row('analytics')`, 'container databases')
    await js(`__t.row('analytics').click()`)
    await wait(`!!__t.row('events')`, 'container tables')
    assert.ok((await js(`__t.row('events').innerText`)).includes('5') , 'row estimate')
    await js(`__t.inst('docker:lab-cache-redis')`)
    await wait(`!!__t.body().querySelector('.db-tile')`, 'redis with requirepass')
    await js(`__t.inst('docker:lab-legacy-mysql')`)
    await wait(`__t.text().includes('8.4') && !!__t.body().querySelector('.db-tile')`, 'mysql 8.4 with the root password of the container', 400)
    await js(`dbBackup(__t.tab(), curInst(__t.tab()), 'mysql'); true`)
    await wait(`!!__t.S().backup`, 'container backup', 600)
    assert.ok(ssh(`gunzip -c ${(await js('__t.S().backup')).path} | head -c 400`).includes('MySQL dump'))

    // ---- a login typed in the panel (TCP, as the SSH account, no sudo) ----
    await js(`api.invoke('db:login', __t.tab().connId, 'local:postgres:5432', { user: 'reporting', pass: 'reporting-pw', database: 'shop' }).then(() => dbDiscover(__t.tab())).then(() => __t.inst('local:postgres:5432'))`)
    await wait(`!!__t.body().querySelector('.db-tile')`, 'overview with a login')
    assert.ok((await js('__t.text()')).includes('identifiant reporting'))
    assert.ok((await js('__t.text()')).includes('reporting'))
    await js(`__t.view('SQL').click()`)
    await wait(`!!__t.S().sql.editor`, 'editor with login')
    await js(`__t.S().sql.readOnly = false; __t.S().sql.db = 'shop'; __t.S().sql.editor.setValue("SELECT count(*) FROM orders; DELETE FROM orders WHERE id = 1;"); runDbScript(__t.tab()); true`)
    await wait(`!!__t.S().sql.results`, 'rights of the login')
    R = await js(`__t.S().sql.results`)
    assert.equal(R.results[0].rows[0][0], '20000')
    assert.match(R.error.message, /permission denied/)
    const saved = JSON.parse(fs.readFileSync(path.join(temp, 'profile', 'Cyberdog', 'db-logins.json'), 'utf8'))
    assert.ok(!JSON.stringify(saved).includes('reporting-pw'), 'the password is encrypted on disk')
    await js(`forgetDbLogin(__t.tab(), curInst(__t.tab()))`)
    await wait(`__t.text().includes('sudo · postgres')`, 'back to automatic')
    await shot('done')
    console.log('Databases UI passed: discovery (services + containers), overview, data pages + structure, SQL read only / write / meta refused, sessions + cancel, roles + grants, backups (pg_dump, mysqldump in a container), logs, MariaDB, Redis keys + commands, container credentials, typed login.')
    app.exit(0)
  } catch (e) { console.error(e); await win.webContents.capturePage().then(i => fs.writeFileSync(path.join(shots, 'db-failure.png'), i.toPNG())).catch(() => {}); app.exit(1) }
}))
require(path.join(root, 'src/main.js'))
